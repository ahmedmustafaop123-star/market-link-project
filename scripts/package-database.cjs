/**
 * Builds the database-only delivery folder and zips it:
 *   public/MarketLink-Database.zip  →  MarketLink-Database/
 *
 * Everything inside comes from the application source, so the scripts always match the live schema:
 *   • PostgreSQL DDL (the database the app really runs on)
 *   • MySQL 8 equivalent DDL
 *   • ERD + table reference
 *   • demo/seed account list and the schema notes from the project docs
 *
 * Usage: node scripts/package-database.cjs
 */
const fs = require("fs");
const path = require("path");
const os = require("os");
const { spawnSync } = require("child_process");

const ROOT = path.resolve(__dirname, "..");
const NAME = "MarketLink-Database";
const STAGE_PARENT = path.join(os.tmpdir(), "ml-db-package");
const STAGE = path.join(STAGE_PARENT, NAME);
const OUT_ZIP = path.join(ROOT, "public", `${NAME}.zip`);
const ts = require(path.join(ROOT, "node_modules/typescript"));

function loadTs(file) {
  const src = fs.readFileSync(path.join(ROOT, file), "utf8");
  const js = ts.transpileModule(src, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2019 } }).outputText;
  const m = { exports: {} };
  new Function("module", "exports", "require", js)(m, m.exports, require);
  return m.exports;
}
const { POSTGRES_DDL } = loadTs("src/lib/ddl-postgres.ts");
const docs = loadTs("src/lib/docs-content.ts");

const write = (rel, content) => {
  const p = path.join(STAGE, rel);
  fs.mkdirSync(path.dirname(p), { recursive: true });
  fs.writeFileSync(p, content);
};
const copy = (from, to) => {
  const src = path.join(ROOT, from);
  if (!fs.existsSync(src)) return false;
  fs.mkdirSync(path.dirname(to), { recursive: true });
  fs.copyFileSync(src, to);
  return true;
};
const countFiles = (dir) => fs.readdirSync(dir, { withFileTypes: true }).reduce((n, d) => n + (d.isDirectory() ? countFiles(path.join(dir, d.name)) : 1), 0);

/* ---------------- stage ---------------- */
fs.rmSync(STAGE_PARENT, { recursive: true, force: true });
fs.mkdirSync(STAGE, { recursive: true });

// 1. PostgreSQL schema — identical to what the running application created.
write("postgresql/01-marketlink-schema.sql", `-- MarketLink Agri-Hub Pakistan · PostgreSQL 14+ schema\n-- Generated from the live application schema (src/lib/ddl-postgres.ts) on ${new Date().toISOString().slice(0, 10)}.\n\n` + POSTGRES_DDL.replace(/--> statement-breakpoint\n?/g, ""));
copy("database/schema.sql", path.join(STAGE, "postgresql/02-generated-schema.sql"));

// 2. MySQL 8 equivalent (portable DDL for review/submission).
write("mysql/01-marketlink-schema-mysql.sql", docs.MYSQL_DDL);
copy("database/mysql_schema.sql", path.join(STAGE, "mysql/02-generated-schema-mysql.sql"));

// 3. Reference material.
write("ERD.txt", `${docs.ERD}\n`);
