// 5. Database guide.
write("README.md", `# MarketLink Agri-Hub Pakistan — Database Package

This folder contains **only the database files** of the project: the schema in PostgreSQL (the
database the application runs on) and the equivalent MySQL 8 script, together with the ERD,
table reference and demo-data notes.

## Folder contents

| File | What it is |
|---|---|
| \`postgresql/01-marketlink-schema.sql\` | **PostgreSQL schema** (tables, enums, indexes, foreign keys) — identical to the schema the app creates |
| \`postgresql/02-generated-schema.sql\` | The same schema as dumped by drizzle-kit (reference copy) |
| \`mysql/01-marketlink-schema-mysql.sql\` | **MySQL 8** translation of the same database |
| \`mysql/02-generated-schema-mysql.sql\` | Reference copy of the MySQL script |
| \`ERD.txt\` | Entity-relationship diagram (text form) |
| \`TABLES.md\` | One-line purpose of every table |
| \`DEMO-DATA.txt\` | Demo accounts the app seeds on first start |
| \`notes/Admin-Guide.md\` | Admin panel guide |
| \`tools/\` | Function audit + escrow-redirect check scripts |

## How the application uses the database

The app runs on **PostgreSQL**. Two modes are supported (see \`.env\`):

1. **Built-in database (default, nothing to install)** — an embedded PostgreSQL (PGlite) stored in
   the \`.data\` folder next to the app. Tables and demo data are created automatically on the first
   start.
2. **Your own PostgreSQL server** — set \`DATABASE_URL=postgresql://user:password@host:5432/app_db\`
   in \`.env\`. The database itself is created automatically if it does not exist, then the schema
   and demo data are applied.

## Loading the schema manually (own server)

\`\`\`bash
# PostgreSQL
createdb app_db
psql -d app_db -f postgresql/01-marketlink-schema.sql

# MySQL 8
mysql -u root -p -e "CREATE DATABASE app_db CHARACTER SET utf8mb4"
mysql -u root -p app_db < mysql/01-marketlink-schema-mysql.sql
\`\`\`

## Verifying the schema matches the live database

Open the app as admin → **/admin/db-explorer**: it lists every table and column read straight from
the running database, and the SQL console can run read-only queries (write mode is audited).
`);

/* ---------------- zip ---------------- */
fs.rmSync(OUT_ZIP, { force: true });
const r = spawnSync("zip", ["-rq", "-X", OUT_ZIP, NAME], { cwd: STAGE_PARENT, stdio: "inherit" });
if (r.status !== 0) { console.error("zip failed"); process.exit(1); }
console.log(`Database package ready: ${OUT_ZIP} | ${countFiles(STAGE)} files | ${(fs.statSync(OUT_ZIP).size / 1024).toFixed(0)} KB`);
console.log(`Folder preview: ${STAGE}`);
