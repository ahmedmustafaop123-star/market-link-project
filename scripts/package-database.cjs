copy("Documentation/7-Admin-Guide.md", path.join(STAGE, "notes/Admin-Guide.md"));
copy("scripts/smoke-test.mjs", path.join(STAGE, "tools/smoke-test.mjs"));
copy("scripts/verify-payment-redirect.cjs", path.join(STAGE, "tools/verify-payment-redirect.cjs"));

